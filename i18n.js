// ─── Core engine ────────────────────────────────────────────────────────────

const LANG_KEY = 'azk_lang';
const SUPPORTED = ['en', 'ru', 'az'];

function getLang() {
  const stored = localStorage.getItem(LANG_KEY);
  if (stored && SUPPORTED.includes(stored)) return stored;
  // Browser default fallback
  const browser = navigator.language.slice(0, 2).toLowerCase();
  return SUPPORTED.includes(browser) ? browser : 'en';
}

function setLang(lang) {
  if (!SUPPORTED.includes(lang)) return;
  localStorage.setItem(LANG_KEY, lang);
  applyLang(lang);
  updateLangUI(lang);
  // Update html lang attribute
  document.documentElement.lang = lang;
}

function applyLang(lang) {
  const t = TRANSLATIONS[lang];
  if (!t) return;

  // Text content via data-i18n
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.dataset.i18n;
    if (t[key] !== undefined) el.textContent = t[key];
  });

  // HTML content via data-i18n-html (for elements that need innerHTML)
  document.querySelectorAll('[data-i18n-html]').forEach(el => {
    const key = el.dataset.i18nHtml;
    if (t[key] !== undefined) el.innerHTML = t[key];
  });

  // Placeholder via data-i18n-placeholder
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.dataset.i18nPlaceholder;
    if (t[key] !== undefined) el.placeholder = t[key];
  });
}

function updateLangUI(lang) {
  document.querySelectorAll('.lang-btn').forEach(btn => {
    const active = btn.dataset.lang === lang;
    btn.classList.toggle('text-on-background', active);
    btn.classList.toggle('font-semibold', active);
    btn.classList.toggle('text-zinc-400', !active);
    btn.classList.toggle('font-normal', !active);
  });
}

// ─── Init ────────────────────────────────────────────────────────────────────

document.addEventListener('DOMContentLoaded', () => {
  const lang = getLang();
  applyLang(lang);
  updateLangUI(lang);
  document.documentElement.lang = lang;

  // Bind lang switcher buttons
  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.addEventListener('click', () => setLang(btn.dataset.lang));
  });
});
